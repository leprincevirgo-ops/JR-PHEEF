"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const vm=require("node:vm");
const html=fs.readFileSync("public/index.html","utf8");
const css=fs.readFileSync("public/jr-public-discovery.css","utf8");
const js=fs.readFileSync("public/jr-public-discovery.js","utf8");
new vm.Script(js,{filename:"public/jr-public-discovery.js"});
const discovery=html.indexOf('<section id="jr-public-discovery"');
const auth=html.indexOf('<section id="auth">');
assert.ok(discovery>=0&&auth>discovery,"public discovery must precede authentication");
assert.match(html,/jr-public-discovery\.css\?v=2/,"public discovery stylesheet must load at the current cache version");
assert.match(html,/jr-public-discovery\.js\?v=2/,"public discovery controller must load at the current cache version");
for(const world of ["dgbo","family","move","link"])assert.match(html,new RegExp('data-world="'+world+'"'),"missing public world: "+world);
assert.match(html,/data-jpd-action="register"/,"public registration CTA is required");
assert.match(html,/data-jpd-action="login"/,"public login CTA is required");
assert.match(html,/function showRegister\(\)/,"existing registration flow must remain available");
assert.match(html,/function showLogin\(\)/,"existing login flow must remain available");
assert.match(js,/window\.showRegister\(\)/,"public registration must call the existing registration view");
assert.match(js,/window\.showLogin\(\)/,"public sign-in must call the existing login view");
assert.match(css,/body\.jr-public-discovery-mode #auth\{display:none!important\}/,"auth must stay hidden during discovery");
assert.match(css,/body\.jr-public-auth-mode #jr-public-discovery\{display:none!important\}/,"discovery must hide during authentication");
assert.match(js,/MutationObserver/,"signed-in app transition must be observed");
assert.match(html,/Capabilities shown are product areas, not a claim that every external service/,"public copy must not overstate integration readiness");
for(const slug of ["dgbo","family","jr-pheef"])assert.ok(js.includes(slug+":")||js.includes('"' + slug + '":'),"missing branded company world: "+slug);
for(const token of ["jpw-hero","jpw-grid","jpw-back","data-jpw-register","data-jpw-login","returnToDiscovery"])assert.ok(js.includes(token),"company website experience missing: "+token);
assert.match(js,/FAMILY does not promise returns/,"FAMILY financial authorisation boundary must remain visible");
assert.match(js,/Separate company records and responsibilities/,"company separation must remain visible");
assert.match(js,/window\.jrPublicShowCompanyWorld/,"company world navigation should be exposed for controlled reuse");
console.log("PASS: public discovery precedes authentication; DGBO, FAMILY and JR PHEEF expose branded in-platform company websites; account flow and safety boundaries remain intact.");
