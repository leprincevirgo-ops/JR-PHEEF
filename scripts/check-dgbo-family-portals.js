"use strict";
const fs=require("node:fs"),assert=require("node:assert/strict"),vm=require("node:vm");
const html=fs.readFileSync("public/index.html","utf8");
const shell=fs.readFileSync("public/workspace-shell.js","utf8");
const intent=fs.readFileSync("public/intent-first-experience.js","utf8");
const routes=fs.readFileSync("routes/jr.js","utf8");
assert.ok(!html.includes('data-page="dgbo"')&&!html.includes('data-page="family"'),"DGBO and FAMILY must not return as technical primary-navigation tabs");
assert.match(html,/<div id="dgbo" class="page hidden">/,"DGBO member portal missing");
assert.match(html,/<div id="family" class="page hidden">/,"FAMILY member portal missing");
assert.match(html,/What you can access/,"DGBO access catalogue missing");
assert.match(html,/FAMILY · FINANCIAL ACCESS &amp; FAMILY COORDINATION/,"FAMILY introduction missing");
assert.match(html,/Idea records &amp; protection[\s\S]*IN DEVELOPMENT/,"DGBO idea-vault readiness must be disclosed");
assert.match(html,/Banking, payments &amp; lending[\s\S]*NOT ACTIVE/,"FAMILY financial-service readiness must be disclosed");
assert.match(shell,/\["dgbo","DGBO"/,"DGBO workspace metadata missing");
assert.match(shell,/\["dgbo","family","ecosystem"/,"DGBO/FAMILY workspace grouping missing");
assert.ok(routes.includes('page: "dgbo"')&&routes.includes('page: "family"'),"DGBO and FAMILY must remain addressable through JR routing");
new vm.Script(intent,{filename:"public/intent-first-experience.js"});
const window={};
vm.runInNewContext(intent,{window,document:{readyState:"loading",addEventListener(){}}});
assert.equal(window.jrIntentRoute("open DGBO"),"dgbo","natural-language DGBO access must route directly");
assert.equal(window.jrIntentRoute("open FAMILY"),"family","natural-language FAMILY access must route directly");
console.log("PASS: DGBO and FAMILY portals remain available through JR natural-language access without technical navigation tabs.");
