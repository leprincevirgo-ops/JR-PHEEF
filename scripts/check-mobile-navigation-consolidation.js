"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const html=fs.readFileSync("public/index.html","utf8");
const css=fs.readFileSync("public/mobile-experience.css","utf8");
const shell=fs.readFileSync("public/workspace-shell.js","utf8");
const home=fs.readFileSync("public/universe-home.js","utf8");
const start=html.indexOf('<nav class="nav jp-primary-nav"');
const end=html.indexOf("</nav>",start);
assert.ok(start>=0&&end>start,"Primary navigation must exist.");
const nav=html.slice(start,end);
const primary=[...nav.matchAll(/<button([^>]*)data-page="([^"]+)"/g)].filter(m=>!m[1].includes("role=\"menuitem\"")).map(m=>m[2]);
assert.deepEqual(primary,["home","explore","assistant","messages"],"Only four direct buttons plus More wrapper should remain in the primary nav.");
assert.equal((nav.match(/class="jp-more-wrap"/g)||[]).length,1,"Exactly one More destination must exist.");
assert.ok(nav.includes('data-page="discover"')&&nav.includes('data-page="browser"')&&nav.includes('data-page="projects"')&&nav.includes('data-page="create"'),"Secondary destinations must remain in More.");
assert.ok(css.includes("position:fixed!important;top:auto!important;bottom:0!important"),"Mobile navigation must be fixed to the bottom.");
assert.ok(css.includes("grid-template-columns:repeat(5,minmax(0,1fr))"),"Mobile navigation must have five equal destinations.");
assert.ok(css.includes(".jp-global-search{display:none!important}"),"The duplicate mobile global search row must be hidden.");
assert.ok(shell.includes("never append workspace buttons to the primary bar"),"Workspace shell must not append more primary navigation buttons.");
assert.ok(!shell.includes('nav.append(b)'),"Workspace shell must not add Connections to the primary navigation.");
assert.ok(home.includes('menu.style.bottom=(window.innerHeight-rect.top+8)+"px"'),"More menu must open above the fixed mobile navigation.");
console.log("PASS: five-destination mobile navigation, grouped secondary destinations, no duplicate search row, and More-menu placement.");
